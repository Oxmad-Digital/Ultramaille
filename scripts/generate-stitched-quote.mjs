// Generates per-glyph SVG subpaths for the "cousu" quote animation on
// /notre-engagement, tracing the letterforms of a script font with
// opentype.js so they can be drawn progressively like a stitched thread.
//
// Usage: node scripts/generate-stitched-quote.mjs <path-to-ttf>

import fs from "node:fs";
import path from "node:path";
import opentype from "opentype.js";

const fontPath = process.argv[2];
if (!fontPath) {
  console.error("Usage: node scripts/generate-stitched-quote.mjs <path-to-ttf>");
  process.exit(1);
}

const OUTPUT_PATHS = {
  fr: path.resolve("src/app/notre-engagement/stitched-quote.fr.ts"),
  en: path.resolve("src/app/notre-engagement/stitched-quote.en.ts"),
};

const VARIANTS = {
  fr: [
    "« La plus petite des graines",
    "peut contenir le plus grand des arbres. »",
  ],
  en: [
    "“The smallest of seeds can hold",
    "the tallest of trees.”",
  ],
};

const FONT_SIZE = 100;
const LINE_HEIGHT = 108;
const PADDING = 12;

const buf = fs.readFileSync(fontPath);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

// opentype.js's Path#toPathData rounds coordinates by string-concatenating
// them into exponential notation (`decimalPart + "e+" + places`), which
// silently yields NaN whenever a coordinate's fractional part is small
// enough to serialize as e.g. "8e-15" (see decimalRoundingCache in
// opentype.js's roundDecimal). That hits real glyph coordinates often
// enough with some fonts (e.g. Caveat) to corrupt whole letters, so we
// round coordinates ourselves instead of calling path.toPathData().
function formatCoord(v, places) {
  const f = 10 ** places;
  return String(Math.round(v * f) / f);
}
function pathToData(pathObj, places) {
  let d = "";
  for (const cmd of pathObj.commands) {
    if (cmd.type === "M") d += `M${formatCoord(cmd.x, places)} ${formatCoord(cmd.y, places)}`;
    else if (cmd.type === "L") d += `L${formatCoord(cmd.x, places)} ${formatCoord(cmd.y, places)}`;
    else if (cmd.type === "C")
      d += `C${formatCoord(cmd.x1, places)} ${formatCoord(cmd.y1, places)} ${formatCoord(cmd.x2, places)} ${formatCoord(cmd.y2, places)} ${formatCoord(cmd.x, places)} ${formatCoord(cmd.y, places)}`;
    else if (cmd.type === "Q")
      d += `Q${formatCoord(cmd.x1, places)} ${formatCoord(cmd.y1, places)} ${formatCoord(cmd.x, places)} ${formatCoord(cmd.y, places)}`;
    else if (cmd.type === "Z") d += "Z";
  }
  return d;
}

function buildVariant(lines) {
  let maxWidth = 0;
  const subpathsD = [];

  lines.forEach((line, i) => {
    const y = PADDING + (i + 1) * LINE_HEIGHT;
    // One Path per glyph (each may hold several contours, e.g. the bowl
    // and counter of an "e"), so it can be filled with its holes intact
    // instead of tracing every contour as an independent stroke.
    const glyphPaths = font.getPaths(line, PADDING, y, FONT_SIZE);
    const lineSubpaths = glyphPaths.map((p) => pathToData(p, 1)).filter((d) => d.length > 0);
    if (lineSubpaths.some((d) => d.includes("NaN"))) {
      throw new Error(`NaN detected while shaping line: "${line}"`);
    }
    subpathsD.push(...lineSubpaths);
    const width = font.getAdvanceWidth(line, FONT_SIZE);
    maxWidth = Math.max(maxWidth, width);
  });

  const viewBoxWidth = Math.ceil(maxWidth + PADDING * 2);
  const viewBoxHeight = Math.ceil(lines.length * LINE_HEIGHT + PADDING * 2);

  return {
    subpaths: subpathsD,
    viewBox: `0 0 ${viewBoxWidth} ${viewBoxHeight}`,
  };
}

const TYPES_HEADER = `// Generated by scripts/generate-stitched-quote.mjs — do not edit by hand.
export type StitchedQuoteVariant = {
  subpaths: string[];
  viewBox: string;
};

const variant: StitchedQuoteVariant = `;

for (const [key, lines] of Object.entries(VARIANTS)) {
  const variant = buildVariant(lines);
  const output = `${TYPES_HEADER}{
  subpaths: ${JSON.stringify(variant.subpaths)},
  viewBox: "${variant.viewBox}",
};

export default variant;
`;
  fs.writeFileSync(OUTPUT_PATHS[key], output);
  console.log(`${key.toUpperCase()}: ${variant.subpaths.length} subpaths, viewBox ${variant.viewBox} -> ${OUTPUT_PATHS[key]}`);
}
